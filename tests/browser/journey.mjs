import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { chromium } from 'playwright-core';

const base = process.env.BASE_URL || 'http://localhost:5173';
const out = 'shots/account-journey';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Africa/Lagos', ignoreHTTPSErrors: process.env.BROWSER_IGNORE_HTTPS_ERRORS === 'true' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.setDefaultTimeout(12_000);
const email = `journey-${Date.now()}@example.test`;
const password = `local-test-${crypto.randomUUID()}`;
try {
  await page.goto(`${base}/app/dashboard`, { waitUntil: 'domcontentloaded' });
  await page.waitForURL('**/login?next=*');
  await page.goto(`${base}/signup`, { waitUntil: 'domcontentloaded' });
  await page.getByLabel('Full name', { exact: true }).fill('Journey Test');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Mobile number', { exact: true }).fill('8031234567');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByLabel('Confirm password', { exact: true }).fill(password);
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.waitForURL('**/app/dashboard');
  await page.getByRole('heading', { name: 'Your collections', exact: true }).waitFor();
  assert.equal(await page.getByText('Sample portal.', { exact: true }).count(), 0);
  await page.goto(`${base}/admin/dashboard`, { waitUntil: 'domcontentloaded' });
  await page.waitForURL('**/app/dashboard');
  await page.evaluate(() => localStorage.setItem('slate-role', 'admin'));
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { name: 'Your collections', exact: true }).waitFor();
  await page.goto(`${base}/app/book`, { waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { name: 'Request a collection', exact: true }).waitFor();
  await page.getByLabel('Collection address', { exact: true }).fill('42 Ewet Housing Estate, Uyo');
  await page.getByLabel('Area in Uyo', { exact: true }).selectOption('Ewet Housing Estate');
  await page.getByRole('button', { name: 'Preferred date', exact: false }).click();
  const calendar = page.getByRole('dialog', { name: 'Preferred date' });
  await calendar.waitFor();
  await page.screenshot({ path: `${out}/calendar-desktop.png` });
  await calendar.locator('button[data-date]:enabled').first().click();
  await page.getByLabel('Notes for the collection team', { exact: false }).fill('Bins are beside the gate. Please call on arrival.');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Send request', exact: true }).click();
  await page.waitForURL(/\/app\/pickups\/[a-f0-9-]+$/);
  const requestUrl = page.url();
  await page.getByRole('heading', { name: 'Slate Home', exact: true }).waitFor();
  assert.match(await page.locator('main').innerText(), /Awaiting review/);
  assert.match(await page.locator('main').innerText(), /42 Ewet Housing Estate/);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('heading', { name: 'Slate Home', exact: true }).waitFor();
  await page.screenshot({ path: `${out}/request-desktop.png` });
  await page.getByRole('link', { name: 'Ask about this request', exact: true }).click();
  await page.getByRole('heading', { name: 'Talk to Slate', exact: true }).waitFor();
  await page.getByLabel('Subject', { exact: true }).fill('Confirm collection access');
  await page.getByLabel('Your message', { exact: true }).fill('The gate opens at eight. Can the team confirm access before visiting?');
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  await page.getByText('Message saved', { exact: true }).waitFor();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('link', { name: /Confirm collection access/ }).waitFor();
  await page.goto(requestUrl, { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Cancel request', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel request', exact: true }).click();
  await page.getByText('Cancelled', { exact: true }).waitFor();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByText('Cancelled', { exact: true }).waitFor();
  await page.goto(`${base}/app/dashboard`, { waitUntil: 'domcontentloaded' });
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: width < 600 ? 844 : 1000 });
    await page.getByRole('heading', { name: 'Your collections', exact: true }).waitFor();
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    assert.equal(overflow, false, `Account dashboard overflow at ${width}px`);
    await page.screenshot({ path: `${out}/dashboard-${width}.png`, fullPage: true });
  }
  await page.evaluate(() => document.documentElement.classList.add('dark'));
  await page.screenshot({ path: `${out}/dashboard-dark.png`, fullPage: true });
  await page.getByRole('button', { name: 'Account', exact: true }).click();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Sign out', exact: true }).click();
  await page.waitForURL(url => url.pathname === '/login');
  await page.goto(requestUrl, { waitUntil: 'domcontentloaded' });
  await page.waitForURL('**/login?next=*');
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.waitForURL(requestUrl);
  await page.getByText('Cancelled', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log('Browser journey passed: guarded routes, registration, role tampering, calendar, saved request, support, cancellation, refresh, responsive layouts, logout and sign-in.');
} finally {
  await context.close();
  await browser.close();
}
